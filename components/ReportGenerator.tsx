
import React, { useState, useCallback } from 'react';
import { REPORT_SECTIONS } from '../constants';
import { generateReportSection } from '../services/geminiService';
import { Loader } from './Loader';
import { Card } from './Card';

/**
 * A component that helps generate boilerplate content for project reports.
 * Users can select a report section, and the component will call the Gemini API
 * to generate relevant text content.
 */
export const ReportGenerator: React.FC = () => {
  // State for the currently selected report section.
  const [selectedSection, setSelectedSection] = useState<string>(REPORT_SECTIONS[0]);
  // State to store the content generated by the API.
  const [generatedContent, setGeneratedContent] = useState<string>('');
  // State to manage the loading indicator.
  const [isLoading, setIsLoading] = useState<boolean>(false);
  // State to store and display any errors.
  const [error, setError] = useState<string | null>(null);

  /**
   * Handles the content generation process when the user clicks the "Generate" button.
   * It calls the `generateReportSection` service and updates the state with the result.
   */
  const handleGenerate = useCallback(async () => {
    setIsLoading(true);
    setError(null);
    setGeneratedContent('');
    try {
      const result = await generateReportSection(selectedSection);
      setGeneratedContent(result);
    } catch (err) {
      setError('Failed to generate content. Please try again.');
    } finally {
      setIsLoading(false);
    }
  }, [selectedSection]);

  return (
    <div className="max-w-4xl mx-auto">
      <h2 className="text-3xl font-bold text-white mb-2">Report Content Generator</h2>
      <p className="text-slate-400 mb-6">Generate boilerplate content for your project report to get started quickly.</p>
      
      {/* User input section */}
      <Card>
        <div className="flex flex-col sm:flex-row items-center space-y-4 sm:space-y-0 sm:space-x-4">
          <select
            value={selectedSection}
            onChange={(e) => setSelectedSection(e.target.value)}
            className="w-full sm:flex-1 bg-slate-700 border border-slate-600 text-white rounded-md px-4 py-2 focus:ring-2 focus:ring-sky-500 focus:outline-none"
          >
            {REPORT_SECTIONS.map((section) => (
              <option key={section} value={section}>
                {section}
              </option>
            ))}
          </select>
          <button
            onClick={handleGenerate}
            disabled={isLoading}
            className="w-full sm:w-auto bg-sky-500 text-white font-bold py-2 px-6 rounded-md hover:bg-sky-600 disabled:bg-slate-600 disabled:cursor-not-allowed flex items-center justify-center transition-colors"
          >
            {isLoading ? <Loader size={20} /> : 'Generate'}
          </button>
        </div>
      </Card>

      {error && <div className="mt-4 text-center text-red-400">{error}</div>}
      
      {/* Display generated content */}
      {generatedContent && (
        <Card className="mt-6 animate-fade-in border border-slate-700">
          <h3 className="text-lg font-semibold text-white mb-3">Generated Content for "{selectedSection}"</h3>
          <p className="text-slate-300 whitespace-pre-wrap leading-relaxed">{generatedContent}</p>
        </Card>
      )}
    </div>
  );
};
